#define TERMLINK_DIRECT_REASON_CHECKS_EXHAUSTED_V4 8u
#define TERMLINK_DIRECT_REASON_QUIC_V4 9u
#define TERMLINK_DIRECT_REASON_PEER_PROOF_V4 10u
#define TERMLINK_DIRECT_REASON_SIGNATURE_TIMEOUT_V4 11u
