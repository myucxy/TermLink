/*
 * ABI V4 is an independent, shadow-only multi-pair direct-path surface.
 * V3 remains frozen and is not extended through reserved storage.
 *
 * One native owner retains one UDP socket from Gather through candidate
 * discovery, connectivity checks, nomination, QUIC, peer proof, and shadow
 * validation. No V4 record may contain a Relay/WSS, session, renderer,
 * Envelope, durable-ACK, reconnect, or application-routing handle.
 */
#define TERMLINK_DIRECT_ABI_VERSION_V4 4u

#define TERMLINK_DIRECT_MAX_STUN_SERVERS_V4 2u
#define TERMLINK_DIRECT_MAX_CANDIDATES_PER_BATCH_V4 8u
#define TERMLINK_DIRECT_MAX_CANDIDATES_TOTAL_V4 32u
#define TERMLINK_DIRECT_MAX_PAIRS_PER_BATCH_V4 8u
#define TERMLINK_DIRECT_MAX_PAIRS_TOTAL_V4 32u
#define TERMLINK_DIRECT_MAX_CONCURRENT_PAIRS_V4 4u
#define TERMLINK_DIRECT_MAX_TICKET_BYTES_V4 2048u
#define TERMLINK_DIRECT_MAX_EVENT_BYTES_V4 2048u
#define TERMLINK_DIRECT_MAX_SIGNATURE_BYTES_V4 128u
#define TERMLINK_DIRECT_MAX_PROOF_NONCE_BYTES_V4 32u

#define TERMLINK_DIRECT_PLATFORM_WINDOWS_V4 1u
#define TERMLINK_DIRECT_PLATFORM_ANDROID_V4 2u

#define TERMLINK_DIRECT_ROLE_INITIATOR_V4 1u
#define TERMLINK_DIRECT_ROLE_RESPONDER_V4 2u

#define TERMLINK_DIRECT_CANDIDATE_HOST_V4 1u
#define TERMLINK_DIRECT_CANDIDATE_SERVER_REFLEXIVE_V4 2u
#define TERMLINK_DIRECT_CARRIER_UDP_QUIC_V4 1u

#define TERMLINK_DIRECT_EVENT_IDENTITY_READY_V4 1u
#define TERMLINK_DIRECT_EVENT_STATE_CHANGED_V4 2u
#define TERMLINK_DIRECT_EVENT_DIRECT_FAILED_V4 3u
#define TERMLINK_DIRECT_EVENT_SIGN_REQUEST_V4 4u
#define TERMLINK_DIRECT_EVENT_CANDIDATE_BATCH_V4 5u
#define TERMLINK_DIRECT_EVENT_PAIR_VALIDATED_V4 6u
#define TERMLINK_DIRECT_EVENT_CHECKS_COMPLETE_V4 7u
#define TERMLINK_DIRECT_EVENT_NOMINATION_READY_V4 8u
#define TERMLINK_DIRECT_EVENT_SHADOW_READY_V4 9u
#define TERMLINK_DIRECT_EVENT_IGNORED_STALE_V4 10u

#define TERMLINK_DIRECT_STATE_RELAY_ONLY_V4 1u
#define TERMLINK_DIRECT_STATE_GATHERING_V4 2u
#define TERMLINK_DIRECT_STATE_CHECKING_V4 3u
#define TERMLINK_DIRECT_STATE_NOMINATION_PENDING_V4 4u
#define TERMLINK_DIRECT_STATE_AUTHENTICATING_V4 5u
#define TERMLINK_DIRECT_STATE_SHADOW_DIRECT_V4 6u

#define TERMLINK_DIRECT_REASON_DISABLED_V4 1u
#define TERMLINK_DIRECT_REASON_INVALID_ABI_V4 2u
#define TERMLINK_DIRECT_REASON_INVALID_EPOCH_V4 3u
#define TERMLINK_DIRECT_REASON_INVALID_PLATFORM_V4 4u
