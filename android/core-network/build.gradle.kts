val buildTermlinkDirectNative by tasks.registering {
    group = "build"
    description = "Builds the shared Rust direct-network core and its JNI bridge."
    inputs.files(
        fileTree(directCoreRoot) {
            include(
                "Cargo.lock",
                "Cargo.toml",
                "crates/**/*.rs",
                "crates/**/Cargo.toml",
                "include/**/*.h",
            )
        },
        fileTree("src/main/cpp"),
    )
    inputs.property("requestedDirectAbis", requestedDirectAbis.map { it.joinToString(",") })
    outputs.dir(generatedDirectNativeRoot)

    doLast {
        val abis = requestedDirectAbis.get()
        check(abis.isNotEmpty() && abis.all(supportedDirectAbis::contains)) {
            "Unsupported TermLink direct native ABI list: $abis"
        }
        check(directCoreRoot.resolve("include/termlink_direct_ffi_v3.h").isFile) {
            "network-core/include/termlink_direct_ffi_v3.h must be generated by the shared network core"
        }
        check(directCoreRoot.resolve("include/termlink_direct_ffi_v4.h").isFile) {
            "network-core/include/termlink_direct_ffi_v4.h must be provided by the shared network core"
        }
        check(directCoreRoot.resolve("include/termlink_direct_ffi_v5.h").isFile) {
            "network-core/include/termlink_direct_ffi_v5.h must be provided by the shared network core"
        }
        for (abi in abis) {
            val buildDir = directNativeBuildRoot.get().dir(abi).asFile
            val outputDir = generatedDirectNativeRoot.get().dir(abi).asFile
            buildDir.mkdirs()
            outputDir.mkdirs()
            val configure = providers.exec {
                isIgnoreExitValue = true
                commandLine(
                    directCmakeExecutable.absolutePath,
                    "-S", file("src/main/cpp").absolutePath,
                    "-B", buildDir.absolutePath,
                    "-G", "Ninja",
                    "-DCMAKE_MAKE_PROGRAM=${directNinjaExecutable.absolutePath}",
                    "-DCMAKE_TOOLCHAIN_FILE=${directAndroidNdkRoot.resolve("build/cmake/android.toolchain.cmake").absolutePath}",
                    "-DANDROID_ABI=$abi",
                    "-DANDROID_PLATFORM=android-26",
                    "-DANDROID_NDK=${directAndroidNdkRoot.absolutePath}",
                    "-DTERMLINK_DIRECT_CORE_ROOT=${directCoreRoot.absolutePath}",
                    "-DTERMLINK_CARGO=${directCargoExecutable.absolutePath}",
                    "-DTERMLINK_JNI_OUTPUT_DIR=${outputDir.absolutePath}",
                    "-DCMAKE_BUILD_TYPE=Release",
                )
            }.result.get()
            check(configure.exitValue == 0) { "Direct JNI CMake configure failed for $abi" }
            val build = providers.exec {
                isIgnoreExitValue = true
                commandLine(
                    directCmakeExecutable.absolutePath,
                    "--build", buildDir.absolutePath,
                    "--target", "termlink_direct_jni",
                )
            }.result.get()
            check(build.exitValue == 0) { "Direct JNI native build failed for $abi" }
        }
    }
}

val verifyTermlinkDirectNativeAlignment by tasks.registering {
    group = "verification"
    description = "Verifies every requested Direct JNI ABI uses 16 KiB ELF LOAD alignment."
    dependsOn(buildTermlinkDirectNative)

    doLast {
        check(directReadelfExecutable.isFile) {
            "Pinned Android NDK llvm-readelf is missing: $directReadelfExecutable"
        }
        for (abi in requestedDirectAbis.get()) {
            val library = generatedDirectNativeRoot.get().dir(abi)
                .file("libtermlink_direct_jni.so").asFile
            check(library.isFile) { "Direct JNI output is missing for $abi: $library" }
            val programHeaders = providers.exec {
                commandLine(directReadelfExecutable.absolutePath, "-lW", library.absolutePath)
            }.standardOutput.asText.get()
            val loadAlignments = programHeaders.lineSequence()
                .map(String::trim)
                .filter { it.startsWith("LOAD ") }
                .map { it.substringAfterLast(' ') }
                .toList()
            check(loadAlignments.isNotEmpty() && loadAlignments.all { it == "0x4000" }) {
                "Direct JNI $abi LOAD alignment must be 0x4000, found $loadAlignments"
            }
        }
    }
}

val verifyTermlinkDirectNativeExports by tasks.registering {
    group = "verification"
    description = "Verifies every requested Direct JNI library exports the complete frozen V5 bridge."
    dependsOn(buildTermlinkDirectNative)

    doLast {
        check(directReadelfExecutable.isFile) {
            "Pinned Android NDK llvm-readelf is missing: $directReadelfExecutable"
        }
        for (abi in requestedDirectAbis.get()) {
            val library = generatedDirectNativeRoot.get().dir(abi)
                .file("libtermlink_direct_jni.so").asFile
            check(library.isFile) { "Direct JNI output is missing for $abi: $library" }
            val dynamicSymbols = providers.exec {
                commandLine(
                    directReadelfExecutable.absolutePath,
                    "--dyn-syms",
                    "--wide",
                    library.absolutePath,
                )
            }.standardOutput.asText.get()
            val actual = dynamicSymbols.lineSequence()
                .map(String::trim)
                .filter { it.contains(directV5JniExportPrefix) }
                .map { it.substringAfterLast(' ') }
                .toCollection(sortedSetOf())
            check(actual == expectedDirectV5JniExports) {
                val missing = expectedDirectV5JniExports - actual
                val unexpected = actual - expectedDirectV5JniExports
                "Direct JNI $abi V5 exports drifted; missing=$missing unexpected=$unexpected"
            }
        }
    }
}

